// Regenerates src/endpoints.ts from Instantly's published OpenAPI spec: `npm run generate`.
import { writeFile } from "node:fs/promises";

const SPEC_URL = "https://api.instantly.ai/openapi/api_v2.json";
const METHODS = ["get", "post", "put", "patch", "delete"];
const MAX_DESCRIPTION = 240;
const MAX_DEPTH = 5;

const spec = await (await fetch(SPEC_URL)).json();

const trim = (text) => (text && text.length > MAX_DESCRIPTION ? `${text.slice(0, MAX_DESCRIPTION)}…` : text);

/** Inlines $refs and drops examples, titles and vendor keys so agents get a small but complete schema. */
function slim(schema, depth = 0) {
  if (Array.isArray(schema)) return schema.map((item) => slim(item, depth));
  if (!schema || typeof schema !== "object") return schema;
  if (schema.$ref) {
    if (depth >= MAX_DEPTH) return { type: "object" };
    const target = schema.$ref.replace("#/", "").split("/").reduce((node, key) => node?.[key], spec);
    return slim(target, depth + 1);
  }
  const out = {};
  for (const [key, value] of Object.entries(schema)) {
    if (["example", "examples", "title", "readOnly", "deprecated"].includes(key) || key.startsWith("x-")) continue;
    if (key === "description") out.description = trim(value);
    else if (key === "properties") {
      out.properties = {};
      for (const [name, prop] of Object.entries(value)) if (!prop?.readOnly) out.properties[name] = slim(prop, depth + 1);
    } else out[key] = slim(value, depth + 1);
  }
  // Some enums are only spelled out in x-enumDescriptions.
  if (!out.enum && schema["x-enumDescriptions"]) out.enum = Object.keys(schema["x-enumDescriptions"]);
  return out;
}

const endpoints = [];
for (const [path, ops] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = ops[method];
    if (!op) continue;
    const description = op.description && op.description !== op.summary ? trim(op.description) : undefined;
    endpoints.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      tag: op.tags?.[0] ?? "Other",
      summary: op.summary ?? op.operationId,
      ...(description && { description }),
      ...(op.parameters?.length && {
        params: op.parameters.map((p) => ({
          name: p.name,
          in: p.in,
          ...(p.required && { required: true }),
          ...(p.description && { description: trim(p.description) }),
          schema: slim(p.schema ?? {}),
        })),
      }),
      ...(op.requestBody?.content?.["application/json"]?.schema && {
        body: slim(op.requestBody.content["application/json"].schema),
      }),
    });
  }
}

const ids = new Set(endpoints.map((e) => e.id));
if (ids.size !== endpoints.length) throw new Error("Duplicate operationIds in spec");

await writeFile(
  new URL("../src/endpoints.ts", import.meta.url),
  `// Generated by scripts/gen-endpoints.mjs from ${SPEC_URL} (spec ${spec.info.version}). Do not edit.
export interface Endpoint {
  id: string;
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  tag: string;
  summary: string;
  description?: string;
  params?: Array<{ name: string; in: "path" | "query"; required?: boolean; description?: string; schema: Record<string, unknown> }>;
  body?: Record<string, unknown>;
}

export const ENDPOINTS: Endpoint[] = ${JSON.stringify(endpoints)};
`,
);
console.log(`Wrote ${endpoints.length} endpoints`);
